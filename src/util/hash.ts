/** FNV-1a 32-bit hash of a UTF-16 string, as 8 lowercase hex chars. Good enough to memoise an SVG. */
export function fnv1a(text: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, '0');
}
