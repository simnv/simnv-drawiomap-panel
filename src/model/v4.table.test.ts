describe('parseConfig over the config table', () => {
  it('holds at least 80 cases with distinct names', () => {
    expect(cases.length).toBeGreaterThanOrEqual(80);
    expect(new Set(cases.map(([name]) => name)).size).toBe(cases.length);
  });

  it.each(cases)('%s', (_name, input) => {
    const parsed = parseConfig(input);
    expect({
      config: parsed.config,
      invalidClasses: [...parsed.invalidClasses],
      invalidOverrides: [...parsed.invalidOverrides],
      report: parsed.report,
    }).toMatchSnapshot();
  });
});
